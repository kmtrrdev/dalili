let lang = "en";
// The URL wins (/ar, ?lang=ar: each language has its own indexable address), then the saved choice, then the browser.
const urlLang = new URLSearchParams(location.search).get("lang") || (/^\/ar(\/|$)/.test(location.pathname) ? "ar" : null);
try { lang = urlLang || localStorage.getItem("lang") || (navigator.language || "en").slice(0, 2); } catch (_) { lang = urlLang || "en"; }
if (!DICT[lang]) lang = "en";

export const getLang = () => lang;
export const locale = () => (lang === "ar" ? "ar-EG" : "en-GB");

/** t("tabs.stay") or t("nights", 3) */
export function t(key, ...args) {
  const val = key.split(".").reduce((o, k) => (o == null ? o : o[k]), DICT[lang]) ??
    key.split(".").reduce((o, k) => (o == null ? o : o[k]), DICT.en);
  return typeof val === "function" ? val(...args) : val ?? key;
}

/** Fill every [data-i18n] / [data-i18n-ph] / [data-i18n-title] element and set the page direction. */
export function applyStatic() {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
    el.setAttribute("aria-label", t(el.dataset.i18nTitle));
  });
}

/** Add a feature's own strings ({ en: {...}, ar: {...} }). */
export function extend(extra) {
  for (const l of Object.keys(extra)) if (DICT[l]) Object.assign(DICT[l], extra[l]);
}

export function setLang(next) {
  lang = DICT[next] ? next : "en";
  try { localStorage.setItem("lang", lang); } catch (_) { /* storage unavailable */ }
  applyStatic();
}
